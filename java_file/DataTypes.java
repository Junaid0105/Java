package java_file;

public class DataTypes {
    public static void main(String[] args){
        byte ByteType = 10; // this data type store 1Byte size value
        System.out.println(ByteType);

        short ShortIntegerNumber = 122; // this data type store 2Byte size
        System.out.println(ShortIntegerNumber);

        int IntegerNumber = 2000; // store 4Byte
        System.out.println(IntegerNumber);

        long LongIntegerValue = 1234567890; //size 8Byte
        System.out.println(LongIntegerValue);

        float FloatNumber = 12.34f; // float data type -- we use f in value for float represent
        System.out.println(FloatNumber);

        char CharacterType = 'A'; // it takes 2Byte
        System.out.println(CharacterType);

        double DoubleFloatNumber = 2233.444; // it stores decimal number of size 8Bytes
        System.out.println(DoubleFloatNumber);

        boolean YesOrNo = true; // also can store
        System.out.println(YesOrNo);
    }
}
